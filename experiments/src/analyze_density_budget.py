"""Candidate-density and ray-budget analysis from the registered campaign records.

Analysis-only: reads results/full_metric_campaign.json (the canonical order-1024
campaign over the registered surface M x d x K/d x seed_set) and reduces it to
the two questions the surface was registered to answer:

  1. Candidate density -- with the ray budget fixed relative to d, what does a
     larger candidate pool M buy in design quality, and what does it cost in
     selection latency?
  2. Ray budget -- with the pool fixed, what is the marginal value of rays
     beyond the identifiability minimum K = d?

No new numerics are run. Every number below is a median (or min/max where
stated) over the five registered seeds of quantities already in the canonical
JSON. Whitened convention throughout (R = diag(||J_col||^2) of the full pool);
raw-coordinate posteriors remain available in the campaign record.

Outputs:
  results/density_budget_analysis.json
  paper/tables/density_budget_analysis.md
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CAMPAIGN = REPO / "results" / "full_metric_campaign.json"
OUT_JSON = REPO / "results" / "density_budget_analysis.json"
OUT_MD = REPO / "paper" / "tables" / "density_budget_analysis.md"

# Slices used for the two headline tables. K/d = 1.5 is the representative
# registered budget (matches the campaign's representative cells); M = 1024 is
# the mid-scale pool for the budget slice.
DENSITY_KOD = 1.5
BUDGET_M = 1024


def med(values):
    return float(statistics.median(values))


def cell_summary(cell):
    seeds = cell["seeds"]
    return {
        "M": cell["M"],
        "d": cell["d"],
        "K": cell["K"],
        "K_over_d": cell["K_over_d"],
        "n_seeds": len(seeds),
        "lambda_min_whitened_median": med([s["lambda_min_whitened"] for s in seeds]),
        "logdet_whitened_median": med([s["logdet_whitened"] for s in seeds]),
        "condition_number_median": med([s["condition_number"] for s in seeds]),
        "posterior_rmse_whitened_median": med(
            [s["posterior_whitened"]["rmse"] for s in seeds]
        ),
        "posterior_rmse_raw_median": med([s["posterior_raw"]["rmse"] for s in seeds]),
        "worst_direction_std_whitened_median": med(
            [s["posterior_whitened"]["worst_direction_std"] for s in seeds]
        ),
        "selection_ms_median": med([1e3 * s["selection_seconds"] for s in seeds]),
        "selection_ms_max": max(1e3 * s["selection_seconds"] for s in seeds),
        "rank_full_all_seeds": all(s["rank"] == cell["d"] for s in seeds),
        "blocked_full_rank_all_seeds": all(s["blocked"]["full_rank"] for s in seeds),
        "blocked_retention_min": min(s["blocked"]["retention"] for s in seeds),
        "blocked_retention_median": med([s["blocked"]["retention"] for s in seeds]),
    }


def fmt(x, nd=3):
    return f"{x:.{nd}f}"


def main():
    data = json.loads(CAMPAIGN.read_text())
    cells = [c for c in data["cells"] if "seeds" in c]
    summaries = [cell_summary(c) for c in cells]
    by_key = {(s["M"], s["d"], s["K_over_d"]): s for s in summaries}

    ms = sorted({s["M"] for s in summaries})
    ds = sorted({s["d"] for s in summaries})
    kods = sorted({s["K_over_d"] for s in summaries})

    n_records = sum(s["n_seeds"] for s in summaries)
    all_full_rank = all(s["rank_full_all_seeds"] for s in summaries)
    all_blocked_full_rank = all(s["blocked_full_rank_all_seeds"] for s in summaries)
    retention_min = min(s["blocked_retention_min"] for s in summaries)

    lines = []
    lines.append("# Candidate density and ray budget: analysis of the registered campaign")
    lines.append("")
    lines.append(
        "Post-registration analysis of `results/full_metric_campaign.json` "
        "(order-1024, registered surface M x d x K/d, seed set "
        f"{data['registered_seed_set']}). No new numerics; every entry is a "
        "median over the five registered seeds. Whitened convention "
        "(R = diag(||J_col||^2) of the full candidate pool); raw-coordinate "
        "posteriors are in the campaign record. Generated by "
        "`experiments/src/analyze_density_budget.py`."
    )
    lines.append("")
    lines.append(
        f"Surface coverage: {len(summaries)} cells x 5 seeds = {n_records} greedy "
        f"records; full rank in {'all' if all_full_rank else 'NOT all'} records; "
        f"pinned 20%-sector blocking kept full rank in "
        f"{'all' if all_blocked_full_rank else 'NOT all'} records "
        f"(worst retention {fmt(retention_min, 3)})."
    )

    # ---- Table A: candidate density at fixed relative budget ----
    lines.append("")
    lines.append(f"## A. Candidate density (K/d = {DENSITY_KOD} fixed)")
    lines.append("")
    lines.append(
        "Whitened metrics are NOT comparable across M: R = diag(||J_col||^2) "
        "is built from each (M, d) pool, so R grows roughly in proportion to "
        "M and the whitened lambda_min of a fixed-quality design falls with M "
        "by construction. Cross-M comparisons below therefore use (i) the "
        "raw-coordinate posterior RMSE, which shares a fixed standard-normal "
        "prior and fixed unit-noise model at every M, and (ii) the declared "
        "rescaling M * lambda_min(whitened): for Fibonacci-sphere pools the "
        "per-ray column-norm statistics are approximately M-independent, so "
        "this removes the pool-size factor in R. Raw RMSE moves little in "
        "absolute terms because the unit-noise prior dominates (declared "
        "convention; absolute precision lives in the clock-precision sweep); "
        "the direction and ordering are the meaningful content."
    )
    lines.append("")
    lines.append(
        "| d | metric | " + " | ".join(f"M = {m}" for m in ms) + " | gain M "
        f"{ms[0]} -> {ms[-1]} |"
    )
    lines.append("|---|---|" + "---|" * (len(ms) + 1))
    density_json = []
    for d in ds:
        row_cells = [by_key[(m, d, DENSITY_KOD)] for m in ms]
        lam_scaled = [m * c["lambda_min_whitened_median"] for m, c in zip(ms, row_cells)]
        rmse_raw = [c["posterior_rmse_raw_median"] for c in row_cells]
        lat = [c["selection_ms_median"] for c in row_cells]
        lines.append(
            f"| {d} | median raw posterior RMSE | "
            + " | ".join(fmt(v, 4) for v in rmse_raw)
            + f" | {fmt(rmse_raw[0] / rmse_raw[-1], 3)}x lower |"
        )
        lines.append(
            f"| {d} | median M * lambda_min (whitened, rescaled) | "
            + " | ".join(fmt(v, 1) for v in lam_scaled)
            + f" | {fmt(lam_scaled[-1] / lam_scaled[0], 2)}x |"
        )
        lines.append(
            f"| {d} | median selection latency (ms) | "
            + " | ".join(fmt(v, 3) for v in lat)
            + f" | {fmt(lat[-1] / lat[0], 1)}x cost |"
        )
        density_json.append(
            {
                "d": d,
                "K_over_d": DENSITY_KOD,
                "raw_rmse_by_M": dict(zip(map(str, ms), rmse_raw)),
                "pool_scaled_lambda_min_by_M": dict(zip(map(str, ms), lam_scaled)),
                "latency_ms_by_M": dict(zip(map(str, ms), lat)),
                "raw_rmse_reduction": rmse_raw[0] / rmse_raw[-1],
                "pool_scaled_lambda_min_gain": lam_scaled[-1] / lam_scaled[0],
                "latency_cost": lat[-1] / lat[0],
            }
        )

    # ---- Table B: ray budget at fixed pool ----
    lines.append("")
    lines.append(f"## B. Ray budget (M = {BUDGET_M} fixed)")
    lines.append("")
    lines.append(
        "R depends only on (M, d), so at fixed M the whitening is identical "
        "across budgets and whitened comparisons along the K/d axis are valid "
        "as-is."
    )
    lines.append("")
    lines.append(
        "| d | metric | "
        + " | ".join(f"K/d = {k:g}" for k in kods)
        + " | gain K/d 1 -> 2 |"
    )
    lines.append("|---|---|" + "---|" * (len(kods) + 1))
    budget_json = []
    for d in ds:
        row_cells = [by_key[(BUDGET_M, d, k)] for k in kods]
        lam = [c["lambda_min_whitened_median"] for c in row_cells]
        rmse = [c["posterior_rmse_whitened_median"] for c in row_cells]
        cond = [c["condition_number_median"] for c in row_cells]
        lines.append(
            f"| {d} | median lambda_min (whitened) | "
            + " | ".join(fmt(v) for v in lam)
            + f" | {fmt(lam[-1] / lam[0], 2)}x |"
        )
        lines.append(
            f"| {d} | median posterior RMSE (whitened) | "
            + " | ".join(fmt(v) for v in rmse)
            + f" | {fmt(rmse[0] / rmse[-1], 2)}x lower |"
        )
        lines.append(
            f"| {d} | median condition number | "
            + " | ".join(fmt(v, 1) for v in cond)
            + f" | {fmt(cond[0] / cond[-1], 1)}x lower |"
        )
        budget_json.append(
            {
                "d": d,
                "M": BUDGET_M,
                "lambda_min_by_K_over_d": dict(zip(map(str, kods), lam)),
                "rmse_by_K_over_d": dict(zip(map(str, kods), rmse)),
                "condition_by_K_over_d": dict(zip(map(str, kods), cond)),
                "lambda_min_gain": lam[-1] / lam[0],
                "rmse_reduction": rmse[0] / rmse[-1],
                "condition_reduction": cond[0] / cond[-1],
            }
        )

    # ---- Diminishing-returns check on the budget axis ----
    lines.append("")
    lines.append("## C. Marginal value along the budget axis")
    lines.append("")
    lines.append(
        "Fractional lambda_min gain per budget step (median over seeds, "
        f"M = {BUDGET_M}). A ratio near 1 means the extra rays no longer buy "
        "worst-direction information."
    )
    lines.append("")
    step_headers = [f"{kods[i]:g} -> {kods[i+1]:g}" for i in range(len(kods) - 1)]
    lines.append("| d | " + " | ".join(step_headers) + " |")
    lines.append("|---|" + "---|" * len(step_headers))
    steps_json = []
    for d in ds:
        lam = [by_key[(BUDGET_M, d, k)]["lambda_min_whitened_median"] for k in kods]
        ratios = [lam[i + 1] / lam[i] for i in range(len(lam) - 1)]
        lines.append(
            f"| {d} | " + " | ".join(f"{fmt(r, 2)}x" for r in ratios) + " |"
        )
        steps_json.append({"d": d, "step_ratios": dict(zip(step_headers, ratios))})

    lines.append("")
    lines.append(
        "Rank is never the constraint on this surface (full rank in every "
        "record, including under blocking); density and budget act purely on "
        "conditioning and posterior precision."
    )
    lines.append("")

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(lines))

    OUT_JSON.write_text(
        json.dumps(
            {
                "source": "results/full_metric_campaign.json",
                "analysis": "post-registration reduction; no new numerics",
                "convention": "whitened, R = diag(||J_col||^2) of full pool; medians over registered seeds",
                "surface": {
                    "M": ms,
                    "d": ds,
                    "K_over_d": kods,
                    "cells": len(summaries),
                    "records": n_records,
                },
                "rank": {
                    "full_rank_all_records": all_full_rank,
                    "blocked_full_rank_all_records": all_blocked_full_rank,
                    "blocked_retention_min": retention_min,
                },
                "density_at_fixed_K_over_d": {"K_over_d": DENSITY_KOD, "rows": density_json},
                "budget_at_fixed_M": {"M": BUDGET_M, "rows": budget_json},
                "budget_step_ratios": steps_json,
                "cell_summaries": summaries,
            },
            indent=2,
        )
    )
    print(f"wrote {OUT_MD.relative_to(REPO)} and {OUT_JSON.relative_to(REPO)}")
    print(
        f"cells={len(summaries)} records={n_records} "
        f"all_full_rank={all_full_rank} blocked_full_rank={all_blocked_full_rank} "
        f"retention_min={retention_min:.3f}"
    )


if __name__ == "__main__":
    main()
